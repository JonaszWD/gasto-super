export function t(key, params = {}) {
  const template = STRINGS[current][key] ?? STRINGS.es[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => (name in params ? String(params[name]) : `{${name}}`));
}

/** Display name for a (Spanish) category label. */
export function tCategory(label) {
  if (!label) return label;
  return CATEGORY_NAMES[current]?.[label] ?? label;
}

/** Fill every [data-i18n] element in `root` with its translation. */
export function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => el.setAttribute("aria-label", t(el.dataset.i18nAria)));
}
