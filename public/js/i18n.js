// All UI strings live here, one table per language. Add a language by copying a table.
export const LOCALES = ["es", "en"];
const STORAGE_KEY = "gs_locale";

function initialLocale() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (LOCALES.includes(saved)) return saved;
  } catch {
    /* storage blocked: fall through */
  }
  return (navigator.language || "es").toLowerCase().startsWith("es") ? "es" : "en";
}

let current = initialLocale();
document.documentElement.lang = current;

export function getLocale() {
  return current;
}

/** Switch language (remembered on this device; the server copy syncs it across devices). */
export function setLocale(lang) {
  if (!LOCALES.includes(lang)) return;
  current = lang;
  document.documentElement.lang = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    /* ignore */
  }
}

